import numpy as np
import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import (Input, Conv1D, MaxPooling1D, LSTM, Dense, Dropout, BatchNormalization)
from tensorflow.keras.callbacks import ModelCheckpoint, EarlyStopping, TensorBoard
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.utils import class_weight
from sklearn.metrics import classification_report, confusion_matrix
import datetime
import joblib
import mlflow
import mlflow.tensorflow
import hashlib
import json
import matplotlib.pyplot as plt
import seaborn as sns

# --- Configuration ---
X_FILE = 'X_data.npz'
Y_FILE = 'y_data.npz'
MODEL_NAME = 'btcusdt_win_loss_model.keras'
SCALER_NAME = 'scaler.joblib'
LOG_DIR = "logs/fit/" + datetime.datetime.now().strftime("%Y%m%d-%H%M%S")

# --- MLflow Setup ---
mlflow.tensorflow.autolog()

with mlflow.start_run() as run:
    # --- Load Data (Generated by the aligned script 1) ---
    print("Loading consolidated data...")
    X = np.load(X_FILE)['data']
    y = np.load(Y_FILE)['data']

    # --- Dataset Tracking ---
    mlflow.log_param("X_FILE", X_FILE)
    mlflow.log_param("Y_FILE", Y_FILE)
    data_hash = hashlib.sha256(X.tobytes()).hexdigest()
    mlflow.log_param("data_hash", data_hash)

    print("Splitting data into training and validation sets...")
    X_train, X_val, y_train, y_val = train_test_split(X, y, test_size=0.2, shuffle=False)

    # --- Log dataset parameters ---
    mlflow.log_param("training_samples", len(X_train))
    mlflow.log_param("validation_samples", len(X_val))

    # --- Feature Scaling ---
    n_samples, n_timesteps, n_features = X_train.shape
    X_train_reshaped = X_train.reshape(-1, n_features)

    scaler = StandardScaler()
    scaler.fit(X_train_reshaped)
    joblib.dump(scaler, SCALER_NAME)
    mlflow.log_artifact(SCALER_NAME)
    print(f"Scaler has been fitted on {n_features} features and saved to {SCALER_NAME}")

    X_train_scaled = scaler.transform(X_train_reshaped).reshape(n_samples, n_timesteps, n_features)
    X_val_scaled = scaler.transform(X_val.reshape(-1, n_features)).reshape(X_val.shape)

    print(f"Training data shape: {X_train_scaled.shape}")
    print(f"Validation data shape: {X_val_scaled.shape}")

    # --- Handle Class Imbalance ---
    class_weights = class_weight.compute_class_weight('balanced', classes=np.unique(y_train), y=y_train)
    class_weights_dict = dict(enumerate(class_weights))
    mlflow.log_param("class_weights", class_weights_dict)
    print(f"Calculated Class Weights: {class_weights_dict}")

    # --- Build the CNN-LSTM Model ---
    # The model architecture remains the same and will adapt to the number of features automatically.
    print("Building the CNN-LSTM model...")
    model = Sequential([
        Input(shape=(n_timesteps, n_features)),
        Conv1D(filters=64, kernel_size=5, activation='relu', padding='same'),
        BatchNormalization(), MaxPooling1D(pool_size=2), Dropout(0.3),
        Conv1D(filters=128, kernel_size=5, activation='relu', padding='same'),
        BatchNormalization(), MaxPooling1D(pool_size=2), Dropout(0.3),
        LSTM(100), Dropout(0.4),
        Dense(64, activation='relu'), BatchNormalization(), Dropout(0.5),
        Dense(1, activation='sigmoid')
    ])
    model.compile(optimizer=tf.keras.optimizers.Adam(learning_rate=0.001), loss='binary_crossentropy', metrics=['accuracy'])
    
    # --- Log model summary ---
    with open("model_summary.txt", "w") as f:
        model.summary(print_fn=lambda x: f.write(x + '\n'))
    mlflow.log_artifact("model_summary.txt")

    # --- Callbacks and Training ---
    callbacks = [
        ModelCheckpoint(MODEL_NAME, monitor='val_loss', verbose=1, save_best_only=True, mode='min'),
        EarlyStopping(monitor='val_loss', patience=15, restore_best_weights=True),
        TensorBoard(log_dir=LOG_DIR, histogram_freq=1)
    ]

    print("\n--- Starting Model Training ---")
    history = model.fit(
        X_train_scaled, y_train,
        epochs=100, batch_size=64, validation_data=(X_val_scaled, y_val),
        class_weight=class_weights_dict, callbacks=callbacks
    )

    print("\n--- Model Training Complete ---")
    print(f"Best model saved to {MODEL_NAME}")

    # --- Evaluation and Logging ---
    print("\n--- Evaluating Model ---")
    y_pred = (model.predict(X_val_scaled) > 0.5).astype("int32")

    # --- Classification Report ---
    report = classification_report(y_val, y_pred, output_dict=True)
    with open("classification_report.json", "w") as f:
        json.dump(report, f, indent=4)
    mlflow.log_artifact("classification_report.json")
    print("Classification Report:")
    print(classification_report(y_val, y_pred))

    # --- Confusion Matrix ---
    cm = confusion_matrix(y_val, y_pred)
    plt.figure(figsize=(8, 6))
    sns.heatmap(cm, annot=True, fmt="d", cmap="Blues")
    plt.title("Confusion Matrix")
    plt.ylabel("Actual")
    plt.xlabel("Predicted")
    plt.savefig("confusion_matrix.png")
    mlflow.log_artifact("confusion_matrix.png")
    print("Confusion matrix saved to confusion_matrix.png")

    # --- Log additional metrics ---
    mlflow.log_metric("val_precision", report["weighted avg"]["precision"])
    mlflow.log_metric("val_recall", report["weighted avg"]["recall"])
    mlflow.log_metric("val_f1-score", report["weighted avg"]["f1-score"])

